using System.Security.Cryptography;
using System.Text.Json.Serialization;

namespace Starlights.RuleSets.DND5E5.Abilities;

/// <summary>
/// The selected generation method and immutable application results, retained across method switches.
/// </summary>
public sealed record AbilityGeneration
{

    /// <summary>
    /// Restores a supported method and any previously generated results.
    /// </summary>
    [JsonConstructor]
    public AbilityGeneration(string method, IReadOnlyList<AbilityRoll> rolls)
    {
        if (method is not ("standard-array" or "point-buy" or "application-rolls" or "physical-dice")
            || rolls.Count is not (0 or 6) || method == "application-rolls" && rolls.Count != 6)
        {
            throw new ArgumentException("The ability generation method or retained results are invalid.");
        }

        Method = method;
        Rolls = Array.AsReadOnly(rolls.ToArray());
    }

    /// <summary>
    /// Gets the canonical method identifier.
    /// </summary>
    public string Method
    {
        get;
    }

    /// <summary>
    /// Gets saved results, never regenerated by reading or calculating.
    /// </summary>
    public IReadOnlyList<AbilityRoll> Rolls
    {
        get;
    }

    /// <summary>
    /// Gets the initial method without invented assignments.
    /// </summary>
    public static AbilityGeneration Default => new("standard-array", []);

    /// <summary>
    /// Generates six independent 4d6-drop-lowest results using unbiased application randomness.
    /// </summary>
    public static IReadOnlyList<AbilityRoll> Roll()
    {
        return Array.AsReadOnly(Enumerable.Range(0, 6).Select(_ =>
                new AbilityRoll(Enumerable.Range(0, 4).Select(_ => RandomNumberGenerator.GetInt32(1, 7)).ToArray())).ToArray());
    }

    /// <summary>
    /// Gets the independently specified point-buy cost for a valid score.
    /// </summary>
    public static int PointCost(int score)
    {
        return score switch
        {
            8 => 0,
            9 => 1,
            10 => 2,
            11 => 3,
            12 => 4,
            13 => 5,
            14 => 7,
            15 => 9,
            _ => throw new ArgumentException("Point-buy scores must be from 8 through 15.")
        };
    }
}
